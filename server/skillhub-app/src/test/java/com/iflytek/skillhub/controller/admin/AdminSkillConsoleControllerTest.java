/**
 * End-to-end HTTP tests for the administrator skill console: platform-wide
 * listing, batch ownership transfer and batch hard delete.
 *
 * <p>Each batch item runs in its own transaction, so this also covers the case
 * where a rejected skill in the middle of a batch must not undo the successful
 * deletions before it.
 */
@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("test")
class AdminSkillConsoleControllerTest {

    private static final String PREFIX = "adminskills-";

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private NamespaceRepository namespaceRepository;

    @Autowired
    private NamespaceMemberRepository namespaceMemberRepository;

    @Autowired
    private UserAccountRepository userAccountRepository;

    @Autowired
    private SkillRepository skillRepository;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    private Long namespaceId;

    @BeforeEach
    void setUp() {
        // Created by Flyway in production, but Flyway is disabled in the test profile;
        // the transfer guard reads it through JdbcTemplate.
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS skill_source_link (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  skill_id BIGINT NOT NULL,
                  source_id BIGINT,
                  repo_url VARCHAR(512) NOT NULL,
                  item_path VARCHAR(512) NOT NULL,
                  ref VARCHAR(128),
                  commit_sha VARCHAR(64) NOT NULL,
                  tree_sha VARCHAR(64) NOT NULL,
                  synced_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
                """);

        saveUser(PREFIX + "admin", "Console Admin", "console@example.com");
        saveUser(PREFIX + "owner", "Console Owner", "owner@example.com");
        saveUser(PREFIX + "target", "Console Target", "target@example.com");
        saveUser(PREFIX + "outsider", "Console Outsider", "outsider@example.com");

        // The in-memory database is shared between test methods of this class, so the
        // fixture is created once and reused afterwards.
        namespaceId = namespaceRepository.findBySlug(PREFIX + "ns")
                .map(Namespace::getId)
                .orElseGet(() -> {
                    Namespace namespace = new Namespace(PREFIX + "ns", "Console Namespace", PREFIX + "admin");
                    namespace.setType(NamespaceType.TEAM);
                    return namespaceRepository.save(namespace).getId();
                });

        ensureMember(PREFIX + "admin", NamespaceRole.OWNER);
        ensureMember(PREFIX + "owner", NamespaceRole.MEMBER);
        ensureMember(PREFIX + "target", NamespaceRole.MEMBER);
    }

    @AfterEach
    void cleanUp() {
        // The context (and therefore the in-memory database) is shared with other
        // test classes, so everything this class created is removed again.
        jdbcTemplate.update("delete from audit_log where actor_user_id like ?", PREFIX + "%");
        jdbcTemplate.update("delete from skill_version where skill_id in "
                + "(select id from skill where namespace_id = ?)", namespaceId);
        jdbcTemplate.update("delete from skill where namespace_id = ?", namespaceId);
        jdbcTemplate.update("delete from namespace_member where namespace_id = ?", namespaceId);
        jdbcTemplate.update("delete from namespace where id = ?", namespaceId);
        jdbcTemplate.update("delete from user_role_binding where user_id like ?", PREFIX + "%");
        jdbcTemplate.update("delete from user_account where id like ?", PREFIX + "%");
    }

    @Test
    void listShowsPrivateAndHiddenSkillsToSkillAdmin() throws Exception {
        skill("list-private", SkillVisibility.PRIVATE, false);
        skill("list-hidden", SkillVisibility.PUBLIC, true);

        mockMvc.perform(get("/api/v1/admin/skills")
                        .param("namespace", PREFIX + "ns")
                        .param("keyword", "list-")
                        .with(authentication(skillAdminAuth(PREFIX + "admin"))))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.code").value(0))
                .andExpect(jsonPath("$.data.total").value(2))
                .andExpect(jsonPath("$.data.items[0].namespaceSlug").value(PREFIX + "ns"))
                .andExpect(jsonPath("$.data.items[0].ownerDisplayName").value("Console Owner"));
    }

    @Test
    void listIsForbiddenForPlainUsers() throws Exception {
        mockMvc.perform(get("/api/v1/admin/skills")
                        .with(authentication(plainUserAuth())))
                .andExpect(status().isForbidden());
    }

    @Test
    void listRejectsAnUnknownNamespace() throws Exception {
        mockMvc.perform(get("/api/v1/admin/skills")
                        .param("namespace", "no-such-" + UUID.randomUUID())
                        .with(authentication(superAdminAuth())))
                .andExpect(status().isBadRequest());
    }

    @Test
    void transferMovesOwnershipAndRejectsTheSecondAttempt() throws Exception {
        Skill skill = skill("transfer-me", SkillVisibility.PUBLIC, false);

        mockMvc.perform(post("/api/v1/admin/skills/batch/transfer")
                        .with(authentication(skillAdminAuth(PREFIX + "admin")))
                        .with(csrf())
                        .contentType("application/json")
                        .content("""
                                {"skillIds":[%d],"toUserId":"%starget"}
                                """.formatted(skill.getId(), PREFIX)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.code").value(0))
                .andExpect(jsonPath("$.data.succeeded[0]").value(skill.getId()))
                .andExpect(jsonPath("$.data.failed").isEmpty());

        assertEquals(PREFIX + "target", skillRepository.findById(skill.getId()).orElseThrow().getOwnerId());

        // Second transfer to the same author is rejected with a readable reason.
        mockMvc.perform(post("/api/v1/admin/skills/batch/transfer")
                        .with(authentication(skillAdminAuth(PREFIX + "admin")))
                        .with(csrf())
                        .contentType("application/json")
                        .content("""
                                {"skillIds":[%d],"toUserId":"%starget"}
                                """.formatted(skill.getId(), PREFIX)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.succeeded").isEmpty())
                .andExpect(jsonPath("$.data.failed[0].skillId").value(skill.getId()))
                .andExpect(jsonPath("$.data.failed[0].reason").isNotEmpty());

        skillRepository.delete(skill);
    }

    @Test
    void transferRejectsNonMembers() throws Exception {
        Skill skill = skill("transfer-outsider", SkillVisibility.PUBLIC, false);

        mockMvc.perform(post("/api/v1/admin/skills/batch/transfer")
                        .with(authentication(skillAdminAuth(PREFIX + "admin")))
                        .with(csrf())
                        .contentType("application/json")
                        .content("""
                                {"skillIds":[%d],"toUserId":"%soutsider"}
                                """.formatted(skill.getId(), PREFIX)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.failed[0].skillId").value(skill.getId()));

        assertEquals(PREFIX + "owner", skillRepository.findById(skill.getId()).orElseThrow().getOwnerId());
    }

    @Test
    void batchDeleteCommitsSuccessfulDeletionsAndReportsMissingOnes() throws Exception {
        Skill doomed = skill("delete-me", SkillVisibility.PUBLIC, false);
        long missingId = 999_999L;

        mockMvc.perform(post("/api/v1/admin/skills/batch/delete")
                        .with(authentication(superAdminAuth()))
                        .with(csrf())
                        .contentType("application/json")
                        .content("""
                                {"skillIds":[%d,%d]}
                                """.formatted(doomed.getId(), missingId)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.code").value(0))
                .andExpect(jsonPath("$.data.succeeded[0]").value(doomed.getId()))
                .andExpect(jsonPath("$.data.failed[0].skillId").value(missingId));

        assertTrue(skillRepository.findById(doomed.getId()).isEmpty(),
                "the successful deletion must be committed even though a sibling id failed");
    }

    @Test
    void batchDeleteIsForbiddenForSkillAdmin() throws Exception {
        Skill skill = skill("delete-forbidden", SkillVisibility.PUBLIC, false);

        mockMvc.perform(post("/api/v1/admin/skills/batch/delete")
                        .with(authentication(skillAdminAuth(PREFIX + "admin")))
                        .with(csrf())
                        .contentType("application/json")
                        .content("""
                                {"skillIds":[%d]}
                                """.formatted(skill.getId())))
                .andExpect(status().isForbidden());

        assertTrue(skillRepository.findById(skill.getId()).isPresent());
    }

    private void saveUser(String id, String displayName, String email) {
        if (userAccountRepository.findById(id).isEmpty()) {
            userAccountRepository.save(new UserAccount(id, displayName, email, null));
        }
    }

    private void ensureMember(String userId, NamespaceRole role) {
        if (namespaceMemberRepository.findByNamespaceIdAndUserId(namespaceId, userId).isEmpty()) {
            namespaceMemberRepository.save(new NamespaceMember(namespaceId, userId, role));
        }
    }

    private Skill skill(String slug, SkillVisibility visibility, boolean hidden) {
        Skill skill = new Skill(namespaceId, PREFIX + slug + "-" + UUID.randomUUID().toString().substring(0, 8),
                PREFIX + "owner", visibility);
        skill.setDisplayName("Console " + slug);
        skill.setCreatedBy(PREFIX + "owner");
        skill.setHidden(hidden);
        return skillRepository.save(skill);
    }

    private UsernamePasswordAuthenticationToken superAdminAuth() {
        PlatformPrincipal principal = new PlatformPrincipal(
                PREFIX + "admin", "Console Admin", "console@example.com", "", "test", Set.of("SUPER_ADMIN"));
        return new UsernamePasswordAuthenticationToken(principal, null,
                List.of(new SimpleGrantedAuthority("ROLE_SUPER_ADMIN")));
    }

    private UsernamePasswordAuthenticationToken skillAdminAuth(String userId) {
        PlatformPrincipal principal = new PlatformPrincipal(
                userId, "Console Admin", "console@example.com", "", "test", Set.of("SKILL_ADMIN"));
        return new UsernamePasswordAuthenticationToken(principal, null,
                List.of(new SimpleGrantedAuthority("ROLE_SKILL_ADMIN")));
    }

    private UsernamePasswordAuthenticationToken plainUserAuth() {
        PlatformPrincipal principal = new PlatformPrincipal(
                PREFIX + "owner", "Console Owner", "owner@example.com", "", "test", Set.of("USER"));
        return new UsernamePasswordAuthenticationToken(principal, null,
                List.of(new SimpleGrantedAuthority("ROLE_USER")));
    }
}